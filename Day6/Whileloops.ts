/* 

Types of loops

1. While - execute the condition first and go to the statement inside the loop
2. Do while - execute the statement once and loops if condition is true
3. For loop - Initialize once; checks the condition; increment or decrement
4. Break - Comes out of the loop, if there is a nested loop - comes out from the inner loop
5. Continue - exists from the current condition and continue to the next loop 

*/